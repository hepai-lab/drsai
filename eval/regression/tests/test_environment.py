def test_environment_prepares_digest_bound_knowledge_and_control_resources(tmp_path: Path) -> None:
    case = CaseCatalog(ROOT).load_cases()["knowledge.grounded"]
    with EnvironmentProvisioner(ROOT, tmp_path).prepare(case) as prepared:
        manifest = prepared.manifest
        assert manifest["knowledge_bases"][0]["knowledge_base_id"] == "regression.opendrsai-runtime"
        assert (prepared.workspace / manifest["knowledge_bases"][0]["reference"]).is_file()
        control = next(item for item in manifest["input_resources"] if item["resource_id"] == "regression-control")
        payload = json.loads(control["content"])
        assert payload["required_capabilities"] == ["knowledge_search"]
        assert payload["network"] == "disabled"
        assert payload["allowed_commands"] == []
        document = payload["knowledge_bases"][0]
        content = base64.b64decode(document["content_base64"])
        assert hashlib.sha256(content).hexdigest() == document["sha256"]
        assert document["sha256"] == manifest["knowledge_bases"][0]["sha256"]
        decoded = content.decode("utf-8")
        assert "一个 Session 可以包含多个 Run" in decoded
        assert "不能覆盖原始 Run" in decoded


def test_environment_embeds_digest_bound_run_fixture_without_source_path(tmp_path: Path) -> None:
    case = CaseCatalog(ROOT).load_cases()["run.inspect_compare"]
    with EnvironmentProvisioner(ROOT, tmp_path).prepare(case) as prepared:
        control = next(item for item in prepared.manifest["input_resources"] if item["resource_id"] == "regression-control")
        payload = json.loads(control["content"])
        fixture = payload["run_fixture"]
        raw = base64.b64decode(fixture["content_base64"])
        assert hashlib.sha256(raw).hexdigest() == fixture["sha256"]
        assert payload["allowed_operations"][0]["operation"] == "run.inspect"
        assert "run.replay" in payload["forbidden_operations"]
        assert "path" not in fixture


