ROOT = Path(__file__).resolve().parents[1]


def test_workspace_fixture_is_isolated_and_digest_is_stable(tmp_path: Path) -> None:
    case = CaseCatalog(ROOT).load_cases()["workspace.readonly.diagnose"]
    provisioner = EnvironmentProvisioner(ROOT, tmp_path)
    with provisioner.prepare(case) as environment:
        assert (environment.workspace / "src" / "runtime_metrics.py").is_file()
        assert directory_digest(environment.workspace) == case.data["environment"]["workspace"]["fixture_sha256"]
        (environment.workspace / "local-only.txt").write_text("isolated", encoding="utf-8")
    source = ROOT / "assets" / "workspaces" / "readonly_diagnosis_v1" / "local-only.txt"
    assert not source.exists()


def test_workspace_digest_ignores_interpreter_and_pytest_cache_files(tmp_path: Path) -> None:
    workspace = tmp_path / "workspace"
    source = workspace / "src" / "module.py"
    source.parent.mkdir(parents=True)
    source.write_text("VALUE = 1\n", encoding="utf-8")
    baseline = directory_digest(workspace)

    bytecode = workspace / "src" / "__pycache__" / "module.cpython-312.pyc"
    bytecode.parent.mkdir(parents=True)
    bytecode.write_bytes(b"generated bytecode")
    pytest_cache = workspace / ".pytest_cache" / "v" / "cache" / "nodeids"
    pytest_cache.parent.mkdir(parents=True)
    pytest_cache.write_text("[]", encoding="utf-8")

    assert directory_digest(workspace) == baseline


def test_workspace_evidence_is_derived_from_actual_before_and_after_bytes(tmp_path: Path) -> None:
    case = CaseCatalog(ROOT).load_cases()["workspace.readonly.diagnose"]
    with EnvironmentProvisioner(ROOT, tmp_path).prepare(case) as environment:
        unchanged = {}
        _enrich_workspace_evidence(unchanged, environment)
        assert unchanged["workspace"]["require_unchanged_file_set"] is True
        assert unchanged["workspace"]["require_unchanged_file_digests"] is True
        assert unchanged["workspace"]["aggregate_sha256_before"] == unchanged["workspace"]["aggregate_sha256_after"]

        target = environment.workspace / "src" / "runtime_metrics.py"
        target.write_text(target.read_text(encoding="utf-8") + "# changed\n", encoding="utf-8")
        changed = {}
        _enrich_workspace_evidence(changed, environment)
        assert changed["workspace"]["require_unchanged_file_set"] is True
        assert changed["workspace"]["require_unchanged_file_digests"] is False
        assert changed["workspace"]["changed_paths"] == ["src/runtime_metrics.py"]


