import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const report = JSON.parse(readFileSync(join(root, "release", "voice-windows-hardware-evidence", "report.json"), "utf8"));
const required = ["windows10", "windows11", "builtinMicrophone", "usbMicrophone", "bluetoothMicrophone", "builtinOutput", "usbOutput", "bluetoothOutput", "permissionDenied", "sleepResume", "deviceUnplug", "networkLoss", "systemSpeech", "twentyTurnStability", "memoryStable", "handleStable", "tempFilesClean", "privacyLogsClean"];
assert.equal(report.schemaVersion, 2);
assert.equal(report.evidenceClass, "physical-windows-device-matrix");
assert.equal(report.ok, true, "Physical Windows device matrix is pending or failed.");
assert.ok(report.tester?.name && report.tester?.signedAt && report.tester?.attestation, "Tester identity, signature time, and attestation are required.");
assert.ok(Array.isArray(report.runs) && report.runs.length > 0);
for (const run of report.runs) assert.ok(run.id && run.osVersion && run.inputDevice && run.outputDevice && run.passed === true && run.checks.length && run.evidence.length, `Incomplete hardware run: ${run.id}`);
assert.ok(required.every((name) => report.checks?.[name] === true && report.runs.some((run) => run.passed && run.checks.includes(name))), "Every check must be covered by a passed physical run.");
const { ok: _ok, integrity, ...payload } = report;
assert.equal(integrity?.algorithm, "sha256");
assert.equal(integrity?.digest, createHash("sha256").update(JSON.stringify(payload)).digest("hex"), "Hardware evidence integrity digest does not match.");
console.log("Windows physical voice-device matrix evidence passed (per-run coverage, attachments, tester attestation, and integrity digest).");
