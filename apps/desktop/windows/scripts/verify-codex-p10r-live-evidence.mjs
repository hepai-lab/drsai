import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "../../../..");
const evidence = JSON.parse(readFileSync(resolve(root, ".artifacts/codex-p10/live-evidence.json"), "utf8"));
assert.equal(evidence.passed, true);
assert(Date.now() - Date.parse(evidence.observedAt) < 24 * 60 * 60 * 1000, "Live evidence is stale");
assert.equal(evidence.runtime.restartVerified, true);
assert.equal(evidence.multiTurn.turnCount, 30);
assert.equal(evidence.multiTurn.threadIdStable, true);
assert.equal(evidence.multiTurn.turnIdsUnique, true);
assert.equal(evidence.multiTurn.contextRetained, true);
assert.equal(evidence.streaming.firstContentBeforeTerminal, true);
assert.equal(evidence.cancellation.verified, true);
assert.equal(evidence.archive.roundTrip, true);
assert(evidence.approval.count >= 1);
assert.equal(evidence.processingOrder.ordered, true);
assert.equal(evidence.workspaceFileOperation.verified, true);
const identity = evidence.backendIdentity;
assert(Number.isInteger(identity.pid) && identity.pid > 0);
assert.equal(identity.binary.source, "codex-desktop");
assert.match(identity.binary.binary_digest, /^sha256:[a-f0-9]{64}$/);
assert.match(identity.binary.schema_digest, /^sha256:[a-f0-9]{64}$/);
assert.equal(identity.binary.release_safe, true);
assert.equal(identity.contract.actual_codex_version, identity.binary.version);
assert.equal(identity.contract.actual_schema_digest, identity.binary.schema_digest);
assert.equal(identity.contract.compatibility, "exact");
const runner = readFileSync(resolve(root, "scripts/verify-codex-runtime-online.py"));
assert.equal(evidence.inputs.runnerDigest, createHash("sha256").update(runner).digest("hex"), "Live runner evidence is stale");
console.log(JSON.stringify({ passed: true, pid: identity.pid, version: identity.binary.version, threadId: evidence.multiTurn.threadId }));
